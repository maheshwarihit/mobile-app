// Builds the public Terms of Service and Privacy Policy web pages
// (mobile/public/terms.html, mobile/public/privacy-policy.html) from the same
// JSON the app shows (mobile/src/lib/legal/*.json), so the two never drift.
// Google Play links to the privacy page. Run from anywhere:
//   node scripts/build-legal-pages.mjs
// The deploy scripts run it before every web export.
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "mobile");
const esc = (s) => s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
const link = (s) =>
  esc(s)
    .replace(/info@vagewell\.com/g, '<a href="mailto:info@vagewell.com">info@vagewell.com</a>')
    .replace(/\+91 93427 03376/g, '<a href="tel:+919342703376">+91 93427 03376</a>');

const PAGES = [
  { json: "terms.json", out: "terms.html", other: { href: "privacy-policy.html", label: "Privacy Policy" } },
  { json: "privacy.json", out: "privacy-policy.html", other: { href: "terms.html", label: "Terms of Service" } },
];

for (const page of PAGES) {
  const doc = JSON.parse(readFileSync(join(root, "src/lib/legal", page.json), "utf8"));
  const p = (arr = []) => arr.map((t) => `  <p>${link(t)}</p>`).join("\n");
  const list = (tag, arr) => (arr?.length ? `  <${tag}>\n${arr.map((t) => `    <li>${link(t)}</li>`).join("\n")}\n  </${tag}>` : "");
  const sections = doc.sections
    .map((s) =>
      [`  <h2>${esc(s.heading)}</h2>`, p(s.paragraphs), list("ul", s.bullets), list("ol", s.numbered), p(s.after)]
        .filter(Boolean)
        .join("\n"),
    )
    .join("\n");
  const html = `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8" />
<meta name="viewport" content="width=device-width, initial-scale=1" />
<title>${esc(doc.title)} — VAgeWell Care</title>
<!-- Generated by scripts/build-legal-pages.mjs from src/lib/legal/${page.json}. Edit the JSON, not this file. -->
<style>
  body { font-family: system-ui, -apple-system, "Segoe UI", sans-serif; background: #eef3f9; color: #1f2937; margin: 0; padding: 24px 16px; line-height: 1.55; }
  main { max-width: 720px; margin: 0 auto; background: #fff; border-radius: 16px; padding: 24px; }
  h1 { font-size: 24px; margin: 0 0 4px; color: #1c7cbe; }
  h2 { font-size: 17px; margin: 24px 0 8px; }
  .updated { color: #6b7280; font-size: 14px; margin: 0 0 16px; }
  li { margin: 6px 0; }
  a { color: #1c7cbe; }
  footer { margin-top: 32px; padding-top: 16px; border-top: 1px solid #e5e7eb; font-size: 14px; }
</style>
</head>
<body>
<main>
  <h1>${esc(doc.title)}</h1>
  <p class="updated">VAgeWell Care · ${esc(doc.updated)}</p>
${p(doc.intro)}
${sections}
  <footer>See also: <a href="${page.other.href}">${page.other.label}</a></footer>
</main>
</body>
</html>
`;
  writeFileSync(join(root, "public", page.out), html);
  console.log(`wrote public/${page.out}`);
}
